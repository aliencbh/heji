#!/bin/sh
set -eu
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" --set=app_password="$DB_PASSWORD" <<'SQL'
CREATE ROLE heji_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT PASSWORD :'app_password';
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO heji_app;
ALTER DEFAULT PRIVILEGES FOR ROLE heji_owner IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO heji_app;
ALTER DEFAULT PRIVILEGES FOR ROLE heji_owner IN SCHEMA public GRANT USAGE, SELECT ON SEQUENCES TO heji_app;
SQL